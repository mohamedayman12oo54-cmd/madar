def normalize_phone(raw: str) -> str:
    """Keep digits only. '+20 100 123 4567' -> '201001234567'.
    Storing a canonical digits-only form means the same real phone
    number can never be registered twice under different formatting,
    and it matches how the frontend sends the value (it strips
    everything but digits before hitting the API)."""
    from .phones import digits_only

    return digits_only(raw)


class User(AbstractUser):
    """
    A single user table serves three distinct roles that log in
    differently (see accounts/serializers.py for the actual lookup
    logic):
      - team:    email + password (created by staff via Django admin only —
                 there is no public "team signup" screen in the product)
      - teacher: phone OR email + password
      - student: phone + password (account is pre-created by a teacher,
                 then "claimed" — phone verified via OTP — by the student)

    `username` (inherited from AbstractUser) is never shown to a human;
    it exists only so we can build on Django's standard user/permission
    machinery. See managers.UserManager.
    """

    class Role(models.TextChoices):
        TEACHER = "teacher", "Teacher"
        STUDENT = "student", "Student"
        TEAM = "team", "Team"

    role = models.CharField(max_length=10, choices=Role.choices)
    name = models.CharField(max_length=150, blank=True)
    email = models.EmailField(blank=True, null=True, unique=True)
    phone = models.CharField(max_length=20, blank=True, null=True, unique=True)

    # Verified means "controls this phone/email" (passed OTP at some point).
    # Team accounts are provisioned directly by staff, so they're verified
    # by construction. is_active additionally gates login for teacher/
    # student accounts still mid-onboarding (see PendingAuth below).
    is_verified = models.BooleanField(default=False)

    # Bumped whenever all of a user's sessions must be cut off (password
    # reset). Embedded in every token as the `sv` claim and checked by
    # accounts.authentication.MadarJWTAuthentication.
    session_version = models.PositiveIntegerField(default=0)

    objects = UserManager()

    first_name = None
    last_name = None

    def __str__(self):
        return self.name or self.email or self.phone or self.username

    def save(self, *args, **kwargs):
        # Never let an empty string collide with other rows under the
        # unique constraint — normalize "" to NULL (multiple NULLs are
        # allowed by a unique constraint; multiple "" would not be).
        if self.email == "":
            self.email = None
        if self.phone:
            self.phone = normalize_phone(self.phone)
        if self.phone == "":
            self.phone = None
        # `username` is internal-only (see class docstring) and normally
        # auto-generated by UserManager.create_user(). Anything that
        # bypasses that (get_or_create, update_or_create, the admin,
        # fixtures, ...) would otherwise leave it blank, and since it's
        # unique, a *second* blank one crashes with an IntegrityError —
        # so guarantee it here too, at the model level, not just in the
        # manager.
        if not self.username:
            from .managers import UserManager as _UM

            self.username = _UM()._generate_username()
        super().save(*args, **kwargs)

    @property
    def initials(self) -> str:
        n = (self.name or "").strip()
        return n[0] if n else "؟"


def generate_otp_code() -> str:
    """A 6-digit OTP from a CRYPTOGRAPHIC generator.

    `random` is a Mersenne Twister: seeded from predictable state and fully
    reconstructible from enough observed outputs, so an attacker who collects
    a few codes could predict the next one. `secrets` draws from the OS CSPRNG.

    `randbelow(1_000_000)` is uniform over the whole range (no modulo bias),
    and the result is formatted — and stored, and compared — as a STRING so
    that a leading zero survives: "001234" must never become 1234.
    """
    return f"{secrets.randbelow(1_000_000):06d}"


def supersede_pending(purpose, target):
    """Invalidate any earlier flow for the same person AND the same purpose.

    Without this, pressing "send code" twice leaves TWO live codes, so an
    older one that leaked still works. Scoped by purpose as well as target so
    cancelling a password reset never cancels an unrelated claim flow.
    """
    return PendingAuth.objects.filter(purpose=purpose, target=target, verified=False).delete()[0]


class PendingAuth(models.Model):
    """
    Backs every multi-step flow (teacher signup, teacher password reset,
    student claim) with a single, stateless, OTP-gated record instead of
    a server-side session — the SPA just carries the returned `id`
    (pending_id) from one step to the next.

    `payload` holds whatever the next step needs. Passwords are NEVER
    stored in plaintext here — only the result of make_password(), which
    is exactly what the column would hold on the User model anyway.
    """

    class Purpose(models.TextChoices):
        TEACHER_SIGNUP = "teacher_signup", "Teacher signup"
        TEACHER_RESET = "teacher_reset", "Teacher password reset"
        STUDENT_CLAIM = "student_claim", "Student claim"
        STUDENT_RESET = "student_reset", "Student password reset"
        PARENT_ACCESS = "parent_access", "Guardian read-only access"

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    purpose = models.CharField(max_length=20, choices=Purpose.choices)
    payload = models.JSONField(default=dict, blank=True)

    # OTP delivery target, kept only for display / resend ("رمز أُرسل إلى ...").
    target = models.CharField(max_length=254, blank=True)

    otp_hash = models.CharField(max_length=128)
    otp_expires_at = models.DateTimeField()
    otp_attempts = models.PositiveSmallIntegerField(default=0)
    otp_sent_at = models.DateTimeField(auto_now_add=True)
    resend_count = models.PositiveSmallIntegerField(default=0)

    verified = models.BooleanField(default=False)
    verified_at = models.DateTimeField(null=True, blank=True)

    created_at = models.DateTimeField(auto_now_add=True)

    MAX_ATTEMPTS = 5          # wrong/any guesses per issued code
    MAX_RESENDS = 3           # new codes per pending flow -> at most
                              # MAX_ATTEMPTS * (MAX_RESENDS + 1) guesses in total
    OTP_TTL_SECONDS = 5 * 60
    PENDING_TTL_MINUTES = 30  # whole flow (incl. the step after OTP) expires

    def set_new_otp(self):
        code = generate_otp_code()
        self.otp_hash = make_password(code)
        self.otp_expires_at = timezone.now() + timedelta(seconds=self.OTP_TTL_SECONDS)
        self.otp_attempts = 0
        self.verified = False
        self.verified_at = None
        return code

    def is_pending_expired(self) -> bool:
        return timezone.now() > self.created_at + timedelta(minutes=self.PENDING_TTL_MINUTES)

    def is_otp_expired(self) -> bool:
        return timezone.now() > self.otp_expires_at

    def check_otp(self, code: str) -> bool:
        return check_password(code, self.otp_hash)

    def __str__(self):
        return f"{self.purpose} · {self.target} · {self.id}"
